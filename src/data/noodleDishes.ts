function createNoodleDish(seed: NoodleDishSeed, index: number): DinnerDish {
  const fatG = Math.max(8, Math.round((seed.calories - seed.proteinG * 4 - 210) / 18));
  const carbsG = Math.max(48, Math.round((seed.calories - seed.proteinG * 4 - fatG * 9) / 4));
  const isSoup = seed.tags.includes("汤");
  const isVegetable = seed.tags.includes("素菜");

  return {
    id: `noodle-${seed.id}`,
    name: seed.name,
    description: seed.description,
    recommendationReason: [
      isSoup ? "适合想吃热乎、完整的一碗粉面" : "不用额外配饭，一碗就能解决晚餐",
      isVegetable ? "蔬菜比例更高，负担轻一点" : "蛋白质和主食都在一碗里，饱腹感稳定",
      seed.tags.includes("快手") ? "准备步骤少，适合工作日晚餐" : "风味明确，适合认真吃一碗主食",
    ],
    weatherContext,
    recommendationScore: 84 + (index % 12),
    nutrition: {
      calories: seed.calories,
      proteinG: seed.proteinG,
      fatG,
      carbsG,
    },
    cooking: {
      timeMinutes: seed.timeMinutes,
      difficulty: seed.difficulty ?? (seed.timeMinutes > 35 ? "medium" : "easy"),
    },
    tags: seed.tags,
    ingredients: [
      { name: seed.protein, amount: seed.tags.includes("素菜") ? "适量" : "250g", category: proteinCategoryForSeed(seed) },
      ...seed.vegetables.map((name) => ({ name, amount: "适量", category: "vegetable" as const })),
      { name: seed.carb, amount: "1-2 份", category: "carb" },
      ...seed.seasonings.map((name) => ({ name, amount: "适量", category: "seasoning" as const })),
    ],
    instructions: [
      "先把粉面按包装时间煮到八九成熟，过水或沥干备用。",
      isSoup ? "另起锅处理汤底和蛋白质，煮出鲜味后放入蔬菜。" : "热锅下油，先把蛋白质和香味来源炒出香气。",
      "加入粉面和调味，按口味调整咸淡、酸辣或浓淡。",
      isSoup ? "最后放入粉面稍煮入味，出锅前补葱花或香油。" : "快速翻拌到粉面均匀挂汁，保持口感不糊不坨。",
    ],
  };
}

export const noodleDishes: DinnerDish[] = noodleDishSeeds.map(createNoodleDish);

function proteinCategoryForSeed(seed: NoodleDishSeed): IngredientCategory {
  if (!seed.tags.includes("素菜")) {
    return "protein";
  }

  if (seed.protein.includes("豆腐")) {
    return "protein";
  }

  if (seed.protein.includes("香菇")) {
    return "vegetable";
  }

  return "seasoning";
}
